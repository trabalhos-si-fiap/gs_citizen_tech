CREATE TABLE users (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR2(320) UNIQUE,
    google_sub VARCHAR2(255) UNIQUE,
    role VARCHAR2(20) DEFAULT 'citizen' NOT NULL,
    reputation NUMBER DEFAULT 0 NOT NULL,
    consent_version VARCHAR2(64),
    consent_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_users_role CHECK (
        role IN ('citizen', 'agency', 'moderator', 'manager', 'admin')
    )
);

CREATE TABLE report_groups (
    id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    canonical_report_id VARCHAR2(36) NOT NULL UNIQUE,
    member_count NUMBER DEFAULT 1 NOT NULL,
    confirmation_count NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT ck_report_groups_counts CHECK (
        member_count >= 1 AND confirmation_count >= 0
    )
);

CREATE TABLE territories (
    territory_id VARCHAR2(64) PRIMARY KEY,
    name VARCHAR2(120) NOT NULL,
    active NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT ck_territories_active CHECK (active IN (0, 1))
);

CREATE TABLE agencies (
    agency_id VARCHAR2(64) PRIMARY KEY,
    name VARCHAR2(160) NOT NULL,
    contact_email VARCHAR2(320) NOT NULL,
    active NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT ck_agencies_active CHECK (active IN (0, 1))
);

CREATE TABLE reports (
    id VARCHAR2(36) PRIMARY KEY,
    protocol VARCHAR2(20) NOT NULL UNIQUE,
    user_id NUMBER,
    group_id NUMBER NOT NULL,
    territory_id VARCHAR2(64) DEFAULT 'municipio_demo' NOT NULL,
    category VARCHAR2(32),
    description VARCHAR2(1000),
    lat NUMBER(9, 6) NOT NULL,
    lon NUMBER(10, 6) NOT NULL,
    geohash VARCHAR2(9) NOT NULL,
    photo_key VARCHAR2(512),
    client_created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    correlation_id VARCHAR2(36) NOT NULL,
    has_photo NUMBER(1) DEFAULT 0 NOT NULL,
    triage_state VARCHAR2(32) DEFAULT 'pending_classification' NOT NULL,
    CONSTRAINT fk_reports_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_reports_group FOREIGN KEY (group_id) REFERENCES report_groups (id),
    CONSTRAINT fk_reports_territory FOREIGN KEY (territory_id)
        REFERENCES territories (territory_id),
    CONSTRAINT ck_reports_lat CHECK (lat BETWEEN -90 AND 90),
    CONSTRAINT ck_reports_lon CHECK (lon BETWEEN -180 AND 180),
    CONSTRAINT ck_reports_photo CHECK (has_photo IN (0, 1)),
    CONSTRAINT ck_reports_category CHECK (
        category IS NULL OR category IN (
            'risco_urbano',
            'transporte_publico',
            'saude_atendimento',
            'a_classificar'
        )
    )
);

ALTER TABLE report_groups ADD CONSTRAINT fk_report_groups_canonical
    FOREIGN KEY (canonical_report_id) REFERENCES reports (id)
    DEFERRABLE INITIALLY DEFERRED;

CREATE INDEX ix_reports_user_received ON reports (user_id, received_at);
CREATE INDEX ix_reports_geohash_received ON reports (geohash, received_at);

CREATE TABLE responsibility_rules (
    rule_id VARCHAR2(64) NOT NULL,
    version NUMBER(6) NOT NULL,
    territory_id VARCHAR2(64) NOT NULL,
    category VARCHAR2(32) NOT NULL,
    subcategory VARCHAR2(64),
    agency_id VARCHAR2(64) NOT NULL,
    deadline_hours NUMBER(6) NOT NULL,
    valid_from TIMESTAMP WITH TIME ZONE NOT NULL,
    valid_to TIMESTAMP WITH TIME ZONE,
    active NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT pk_responsibility_rules PRIMARY KEY (rule_id, version),
    CONSTRAINT fk_rules_territory FOREIGN KEY (territory_id)
        REFERENCES territories (territory_id),
    CONSTRAINT fk_rules_agency FOREIGN KEY (agency_id)
        REFERENCES agencies (agency_id),
    CONSTRAINT ck_rules_version CHECK (version >= 1),
    CONSTRAINT ck_rules_deadline CHECK (deadline_hours > 0),
    CONSTRAINT ck_rules_active CHECK (active IN (0, 1)),
    CONSTRAINT ck_rules_validity CHECK (valid_to IS NULL OR valid_to > valid_from)
);

CREATE INDEX ix_rules_lookup ON responsibility_rules (
    territory_id, category, subcategory, active, valid_from, version
);

CREATE TABLE report_comments (
    id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    report_id VARCHAR2(36) NOT NULL,
    user_id NUMBER NOT NULL,
    content VARCHAR2(1000 CHAR) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_report_comments_report FOREIGN KEY (report_id) REFERENCES reports (id),
    CONSTRAINT fk_report_comments_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_report_comments_content CHECK (LENGTH(TRIM(content)) > 0)
);

CREATE INDEX ix_report_comments_report ON report_comments (report_id, created_at, id);

CREATE TABLE confirmations (
    target_id NUMBER NOT NULL,
    user_id NUMBER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_confirmations PRIMARY KEY (target_id, user_id),
    CONSTRAINT fk_confirmations_group FOREIGN KEY (target_id) REFERENCES report_groups (id),
    CONSTRAINT fk_confirmations_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE report_events (
    id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    report_id VARCHAR2(36) NOT NULL,
    type VARCHAR2(40) NOT NULL,
    actor VARCHAR2(128) NOT NULL,
    justification VARCHAR2(2000),
    deadline TIMESTAMP WITH TIME ZONE,
    payload CLOB,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_report_events_report FOREIGN KEY (report_id) REFERENCES reports (id),
    CONSTRAINT ck_report_events_type CHECK (
        type IN (
            'recebido',
            'encaminhado',
            'em_andamento',
            'resolvido',
            'reaberto',
            'contestado',
            'classificado',
            'classificacao_confirmada',
            'classificacao_corrigida',
            'enviado_moderacao',
            'vinculado_grupo',
            'confirmacao_adicionada',
            'cobrado',
            'sinalizado'
        )
    )
);

CREATE INDEX ix_report_events_report_id ON report_events (report_id, id);

CREATE TABLE job_queue (
    id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    report_id VARCHAR2(36) NOT NULL,
    etapa VARCHAR2(64) NOT NULL,
    status VARCHAR2(20) DEFAULT 'pending' NOT NULL,
    attempts NUMBER DEFAULT 0 NOT NULL,
    next_run_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    locked_by VARCHAR2(128),
    lease_until TIMESTAMP WITH TIME ZONE,
    last_error VARCHAR2(256),
    CONSTRAINT fk_job_queue_report FOREIGN KEY (report_id) REFERENCES reports (id),
    CONSTRAINT uq_job_queue_report_stage UNIQUE (report_id, etapa),
    CONSTRAINT ck_job_queue_status CHECK (
        status IN ('pending', 'processing', 'completed', 'failed')
    ),
    CONSTRAINT ck_job_queue_attempts CHECK (attempts >= 0)
);

CREATE INDEX ix_job_queue_status_run
    ON job_queue (status, next_run_at, lease_until, id);

CREATE TABLE notification_links (
    report_id VARCHAR2(36) NOT NULL,
    user_id NUMBER NOT NULL,
    push_token VARCHAR2(512),
    CONSTRAINT pk_notification_links PRIMARY KEY (report_id, user_id),
    CONSTRAINT fk_notification_report FOREIGN KEY (report_id) REFERENCES reports (id),
    CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX ix_notification_links_user ON notification_links (user_id);

CREATE TABLE notification_devices (
    push_token VARCHAR2(512) PRIMARY KEY,
    user_id NUMBER NOT NULL,
    platform VARCHAR2(16) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_notification_devices_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_notification_devices_platform CHECK (
        platform IN ('android', 'ios')
    )
);

CREATE INDEX ix_notification_devices_user ON notification_devices (user_id);

CREATE TABLE audit_log (
    id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    actor_user_id NUMBER,
    action VARCHAR2(64) NOT NULL,
    resource_type VARCHAR2(64) NOT NULL,
    resource_id VARCHAR2(128),
    justification VARCHAR2(2000),
    correlation_id VARCHAR2(36),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX ix_audit_log_created ON audit_log (created_at, id);

CREATE TABLE otp_challenges (
    email VARCHAR2(320) PRIMARY KEY,
    code_hash VARCHAR2(64) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    attempts NUMBER DEFAULT 0 NOT NULL,
    consent_version VARCHAR2(64),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_otp_attempts CHECK (attempts BETWEEN 0 AND 5)
);

CREATE TABLE refresh_tokens (
    token_hash VARCHAR2(64) PRIMARY KEY,
    user_id NUMBER NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    rotated_from VARCHAR2(64),
    revoked_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_refresh_tokens_parent FOREIGN KEY (rotated_from)
        REFERENCES refresh_tokens (token_hash)
);

CREATE INDEX ix_refresh_tokens_user ON refresh_tokens (user_id);
CREATE INDEX ix_refresh_tokens_expiry ON refresh_tokens (expires_at);

